import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { catalogRoles, catalogSkills, skillsById } from '../backend/src/catalog/catalog.js';

const quote = (value: string) => `'${value.replaceAll("'", "''")}'`;
const rows = catalogSkills.map(
  (skill) =>
    `(${[
      skill.databaseId,
      skill.name,
      skill.name
        .toLowerCase()
        .replace(/\+/g, 'plus')
        .replace(/#/g, 'sharp')
        .replace(/[^a-z0-9]/g, ''),
      skill.category,
    ]
      .map(quote)
      .join(
        ',',
      )}, ARRAY[${skill.aliases.map((alias) => quote(alias.toLowerCase().replace(/[^a-z0-9]/g, ''))).join(',')}]::text[])`,
);
const roles = catalogRoles.map(
  (role) =>
    `(${[role.databaseId, role.id, role.name, role.description].map(quote).join(',')}, CURRENT_TIMESTAMP)`,
);
const importance = { core: 3, important: 2, 'nice-to-have': 1 };
const requirements = catalogRoles.flatMap((role) =>
  role.skills.map(
    (skill) =>
      `(${quote(role.databaseId)}, ${quote(skillsById.get(skill.skillId)!.databaseId)}, ${quote(skill.requiredLevel.toUpperCase())}::"Proficiency", ${skill.weight * importance[skill.importance]})`,
  ),
);
const sql = `-- Generated by npm run catalog:seed. Additive catalog expansion; saved roadmaps remain unchanged.
INSERT INTO "Skill" ("id", "name", "normalizedName", "category", "aliases") VALUES
${rows.join(',\n')}
ON CONFLICT ("id") DO UPDATE SET "category"=EXCLUDED."category", "aliases"=EXCLUDED."aliases";
INSERT INTO "RoleTemplate" ("id", "slug", "title", "description", "updatedAt") VALUES
${roles.join(',\n')}
ON CONFLICT ("id") DO UPDATE SET "description"=EXCLUDED."description", "updatedAt"=CURRENT_TIMESTAMP;
-- Only replace template requirements. Goals, user skills, roadmap snapshots and progress are retained.
DELETE FROM "RoleRequirement" WHERE "roleTemplateId" IN (${catalogRoles.map((role) => quote(role.databaseId)).join(',')});
INSERT INTO "RoleRequirement" ("roleTemplateId", "skillId", "requiredLevel", "weight") VALUES
${requirements.join(',\n')};
`;
const migration = process.argv[2] ?? '20261101000100_career_catalog';
if (!/^\d{14}_[a-z0-9_]+$/.test(migration))
  throw new Error('Use a timestamped migration name without path separators.');
const destination = new URL(`../backend/prisma/migrations/${migration}/`, import.meta.url);
mkdirSync(destination, { recursive: true });
const output = new URL('migration.sql', destination);
if (existsSync(output)) {
  if (readFileSync(output, 'utf8') !== sql)
    throw new Error(
      'Existing migration differs. Choose a NEW timestamped migration name; applied migrations must not be overwritten.',
    );
} else writeFileSync(output, sql, { flag: 'wx' });
console.log(
  `Catalog migration generated: ${catalogSkills.length} skills, ${catalogRoles.length} roles, ${requirements.length} requirements`,
);
